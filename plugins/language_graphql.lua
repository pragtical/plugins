-- mod-version:3
local syntax = require "core.syntax"

syntax.add {
  name = "GraphQL",
  files = { "%.graphql$", "%.gql$" },
  comment = "#",
  patterns = {
    { pattern = { '"""', '"""', "\\" },        type = "string"   },
    { pattern = "#.*",                         type = "comment"  },
    { pattern = { '"', '"', "\\" },            type = "string"   },
    { regex = [[-?(?:0|[1-9][0-9]*)(?:\.[0-9]+)?(?:[eE][+-]?[0-9]+)?]],
      type = "number"
    },
    { pattern = "%.%.%.",                      type = "operator" },
    { pattern = "%s*[@]%s*[%a_][%w_]*",        type = "function" },
    { pattern = "!",                           type = "operator" },
    { pattern = "%s*=%s*",                     type = "operator" },
    { pattern = "%s*%$[%a_][%w_]*:*",          type = "literal"  },
    { pattern = "query%s*()[%a_][%w_]*[(]",    type = { "keyword", "function" } },
    { pattern = "mutation%s*()[%a_][%w_]*[(]", type = { "keyword", "function" } },
    { pattern = "[%a_][%w_]*",                 type = "symbol"   },
  },
  symbols = {
    ["Int"]           = "keyword2",
    ["Float"]         = "keyword2",
    ["String"]        = "keyword2",
    ["Boolean"]       = "keyword2",
    ["ID"]            = "keyword2",
    ["query"]         = "keyword",
    ["mutation"]      = "keyword",
    ["subscription"]  = "keyword",
    ["type"]          = "keyword",
    ["interface"]     = "keyword",
    ["input"]         = "keyword",
    ["fragment"]      = "keyword",
    ["directive"]     = "keyword",
    ["extends"]       = "keyword",
    ["implements"]    = "keyword",
    ["on"]            = "keyword",
    ["enum"]          = "keyword",
    ["scalar"]        = "keyword",
    ["union"]         = "keyword",
    ["schema"]        = "keyword",
    ["extend"]        = "keyword2",
    ["true"]          = "literal",
    ["false"]         = "literal",
    ["null"]          = "literal",
  },
}
